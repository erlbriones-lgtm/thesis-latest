const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Custom compile-time HTML include plugin to support separate files without breaking the app
function htmlIncludePlugin() {
  return {
    name: 'html-include',
    transformIndexHtml(html) {
      const includeRegex = /<!--\s*#include\s+"([^"]+)"\s*-->|<include\s+src="([^"]+)"\s*\/>/g;
      let matched = true;
      let processedHtml = html;
      
      while (matched) {
        matched = false;
        processedHtml = processedHtml.replace(includeRegex, (match, p1, p2) => {
          matched = true;
          const fileName = p1 || p2;
          const filePath = path.resolve(process.cwd(), fileName);
          if (fs.existsSync(filePath)) {
            return fs.readFileSync(filePath, 'utf-8');
          } else {
            console.warn(`[html-include] File not found: ${filePath}`);
            return `<!-- Error: ${fileName} not found -->`;
          }
        });
      }
      return processedHtml;
    }
  };
}

// LINT.IfChange(aistudio_media_plugin)
function aistudioMediaPlugin() {
  return {
    name: 'vite-plugin-aistudio-media',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url && req.url.startsWith('/assets/aistudio/')) {
          const rawPath = req.url.split('?')[0].split('#')[0];
          try {
            const decodedPath = decodeURIComponent(rawPath);
            const relativePath = decodedPath.replace(/^\//, '');
            const aistudioDir = path.resolve(
              __dirname,
              'public',
              'assets',
              'aistudio',
            );
            const filePath = path.resolve(__dirname, 'public', relativePath);
            if (
              filePath.startsWith(aistudioDir + path.sep) &&
              fs.existsSync(filePath) &&
              fs.statSync(filePath).isFile()
            ) {
              const ext = path.extname(filePath).toLowerCase();
              const mimeMap = {
                '.jpg': 'image/jpeg',
                '.jpeg': 'image/jpeg',
                '.png': 'image/png',
                '.gif': 'image/gif',
                '.webp': 'image/webp',
                '.svg': 'image/svg+xml',
                '.bmp': 'image/bmp',
                '.ico': 'image/x-icon',
                '.mp4': 'video/mp4',
                '.webm': 'video/webm',
                '.ogv': 'video/ogg',
                '.mp3': 'audio/mpeg',
                '.wav': 'audio/wav',
                '.ogg': 'audio/ogg',
                '.pdf': 'application/pdf',
              };
              res.setHeader(
                'Content-Type',
                mimeMap[ext] || 'application/octet-stream',
              );
              res.setHeader('Cache-Control', 'no-cache');
              fs.createReadStream(filePath).pipe(res);
              return;
            }
          } catch {
            // Fall through if URI decoding or file access fails
          }
        }
        next();
      });
    },
  };
}
